static int TD080B_cmd_list(struct mipi_dsi_device *dsi,
                                   struct cmd_set_entry const *cmd_set,
                                   size_t count)
{
        size_t i;
        int ret = 0;

        for (i = 0; i < count; i++) {
                const struct cmd_set_entry *entry = cmd_set++;
                if(entry->len==1){
                        u8 buffer2[2] = { entry->cmd, entry->param1 };

                        ret = mipi_dsi_generic_write(dsi, &buffer2, sizeof(buffer2));
                }else if(entry->len==3){
                        u8 buffer4[4] = { entry->cmd, entry->param1, entry->param2, entry->param3};
                        ret = mipi_dsi_generic_write(dsi, &buffer4, sizeof(buffer4));

                }
                if (ret < 0)
                        return ret;
        }

        return ret;
};

static int TD080B_enable(struct udevice *dev)
{
	struct rm67191_panel_priv *priv = dev_get_priv(dev);
	struct mipi_dsi_panel_plat *plat = dev_get_plat(dev);
	struct mipi_dsi_device *dsi = plat->device;
	u8 color_format = color_format_from_dsi_format(priv->format);
	//u16 brightness;
	int ret;

	dsi->mode_flags |= MIPI_DSI_MODE_LPM; 
	/* reset panel */
	ret = dm_gpio_set_value(&priv->reset, true);
	if (ret)
		printf("reset gpio fails to set true\n");
	mdelay(100);
	ret = dm_gpio_set_value(&priv->reset, false);
	if (ret)
		printf("reset gpio fails to set true\n");
	mdelay(100);

	//ret = TD080B_set_cmd(dsi);
	ret = TD080B_cmd_list(dsi,
                                      &init_reg[0],
                                      ARRAY_SIZE(init_reg));
	if(ret < 0){
		printf("TD080B write cmd err(%d) \n", ret);	
		return -EIO;
	}

	/* Set pixel format */
	ret = mipi_dsi_dcs_set_pixel_format(dsi, color_format);
	if (ret < 0) {
		printf("Failed to set pixel format (%d)\n", ret);
		return -EIO;
	}

	/* Exit sleep mode */
	ret = mipi_dsi_dcs_exit_sleep_mode(dsi);
	if (ret < 0) {
		printf("Failed to exit sleep mode (%d)\n", ret);
		return -EIO;
	}

	mdelay(120);

	ret = mipi_dsi_dcs_set_display_on(dsi);
	if (ret < 0) {
		printf("Failed to set display ON (%d)\n", ret);
		return -EIO;
	}

	mdelay(100);
	
	 


	return 0;
}
